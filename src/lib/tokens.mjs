import fs from 'node:fs';
import path from 'node:path';

// One source for site CSS, pre-rendered diagrams, server-rendered charts and motion scenes.
export const tokens = JSON.parse(fs.readFileSync(path.join(process.cwd(), 'src/styles/visual-tokens.json'), 'utf8'));
export const cssVar = key => `--${key.replace(/[A-Z]/g, c => '-' + c.toLowerCase()).replace(/(\D)(\d)/g, '$1-$2')}`;

export function tokensCss() {
  const block = (selector, values) => `${selector}{${Object.entries(values).map(([k, v]) => `${cssVar(k)}:${v}`).join(';')}}`;
  return `/* Generated by scripts/build-tokens.mjs from visual-tokens.json. Do not edit. */\n${block(':root', tokens.themes.light)}\n${block(':root[data-theme=dark]', tokens.themes.dark)}\n`;
}

const luminance = hex => {
  const [r, g, b] = hex.slice(1).match(/\w\w/g).map(x => parseInt(x, 16) / 255).map(c => c <= .04045 ? c / 12.92 : ((c + .055) / 1.055) ** 2.4);
  return .2126 * r + .7152 * g + .0722 * b;
};
export function contrast(a, b) {
  const [x, y] = [luminance(a), luminance(b)];
  return (Math.max(x, y) + .05) / (Math.min(x, y) + .05);
}
